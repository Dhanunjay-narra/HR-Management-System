class JobCatalogTaxonomyService:
    @classmethod
    def get_role_by_code(cls, job_code: str) -> EnterpriseJobProfile:
        return MASTER_JOB_CATALOG_DATA.get(job_code)

    @classmethod
    def get_roles_by_department(cls, department: str) -> List[EnterpriseJobProfile]:
        return [p for p in MASTER_JOB_CATALOG_DATA.values() if p.department.lower() == department.lower()]

    @classmethod
    def get_all_roles(cls) -> List[EnterpriseJobProfile]:
        return list(MASTER_JOB_CATALOG_DATA.values())
